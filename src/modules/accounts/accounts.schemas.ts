import { z } from 'zod';

/** Fields the system owns. Sending them is an error rather than being silently ignored. */
const systemField = (message: string) => z.never({ error: message }).optional();

export const createAccountBody = z.object({
  name: z.string().trim().min(1, 'Name cannot be empty').max(100, 'Name must be at most 100 characters'),
  balance: systemField('The initial balance is always 0 and cannot be set'),
  id: systemField('The account id is generated by the system'),
  created_at: systemField('created_at is generated by the system'),
});
export type CreateAccountBody = z.infer<typeof createAccountBody>;
