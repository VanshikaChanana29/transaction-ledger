import { TransactionType } from '@prisma/client';
import { z } from 'zod';
import { amountSchema } from '../../lib/money';

/** Accepts "credit", "Credit" or " DEBIT ". */
const transactionType = z.preprocess(
  (v) => (typeof v === 'string' ? v.trim().toLowerCase() : v),
  z.enum(TransactionType, {
    error: (issue) => (issue.input === undefined ? 'This field is required' : "Type must be 'credit' or 'debit'"),
  }),
);

const systemField = (message: string) => z.never({ error: message }).optional();

export const addTransactionBody = z
  .object({
    type: transactionType,
    amount: amountSchema,
    description: z.string().trim().min(1, 'Description cannot be empty').max(255, 'Description must be at most 255 characters'),
    reference_id: z.string().trim().min(1, 'reference_id cannot be empty').max(100, 'reference_id must be at most 100 characters'),
    id: systemField('The transaction id is generated by the system'),
    created_at: systemField('created_at is generated by the system'),
    // account_id comes from the URL; a value in the body is ignored.
  })
  .transform(({ type, amount, description, reference_id }) => ({ type, amount, description, referenceId: reference_id }));
export type AddTransactionBody = z.infer<typeof addTransactionBody>;

export const listTransactionsQuery = z.object({
  type: transactionType.optional(),
  page: z.coerce.number().int().min(1).default(1),
  limit: z.coerce.number().int().min(1).max(100).default(10),
});
export type ListTransactionsQuery = z.infer<typeof listTransactionsQuery>;
